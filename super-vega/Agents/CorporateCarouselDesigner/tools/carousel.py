#!/usr/bin/env python3
"""The Corporate Carousel Designer's tool. One entry point for every step of a carousel row, so the designer
only ever runs `python3` (Atlas's approved commands have no `bash`, no `cd` and no `$(...)`).
The shell scripts beside it (scrape.sh, render.sh) are run from here. Images are generated by the agent with
submit_ai_job / wait_ai_job (never from this tool); `record-job` only writes the finished job into the metadata.

  python3 "<carousel>/tools/carousel.py" new "<Brand>" <Task ID> --brand-number <n>
          [--product "<product name>"] [--website <url>] [--angle "<topic angle>"]
      Makes the carousel folder Project/<BrandName>/carousels/<TaskID>-<brandname>-<MM-DD>/
      (research/ gen/ out/ deletable/) and its metadata Project/<BrandName>/metadata/<same name>.json,
      with the start time. On a resumed session it prints the existing ones (same Task ID).
      Prints {"folder", "metadata", "name", "started"}.
  python3 "<carousel>/tools/carousel.py" scrape "<folder>" "<url>"
      Runs scrape.sh into <folder>/research/ (page.txt, meta.json, links.txt, style.json, images.txt, img/).
  python3 "<carousel>/tools/carousel.py" record-job "<folder>" <jobId> <credits> "<out.png>" [--url <resultUrl>]
          [--model gpt-image-2] [--status COMPLETED] [--prompt "<prompt>"]
      Records a generation the agent ran with submit_ai_job / wait_ai_job: jobId, model, resultUrl, credits
      (the live price for that size and resolution, marked "credits_source": "price"), status and prompt go
      into the metadata's "jobs" and jobs.jsonl, and "total_credits" is updated. Record a failed job too
      (it may have been billed), with its credits.
  python3 "<carousel>/tools/carousel.py" render "<folder>" <N> ["2 5"]
      Runs render.sh: <folder>/slides.html -> <folder>/out/slide-01.jpg ... and out/contact.png.
  python3 "<carousel>/tools/carousel.py" check "<folder>"
      Confirms the finished carousel without changing it: N slides at 1080x1350, contact.png,
      notes.md with captions, slides.html, the metadata. Prints {"ok", "slides", "total_credits", "problems"}.
  python3 "<carousel>/tools/carousel.py" finish "<folder>" [--theme dark|light] [--headline "<cover>"]
      Writes the slides, the outputs and the totals into the metadata, and the minutes since the start.
      Prints {"folder", "slides", "total_credits", "minutes"}.

<folder> is the carousel folder (absolute, or relative to the Super Vega folder). It must be inside
Project/<BrandName>/carousels/.
"""
import fcntl, json, os, re, subprocess, sys
from datetime import datetime
from pathlib import Path

TOOLS = Path(__file__).resolve().parent
CAROUSEL = TOOLS.parent
SUPER = CAROUSEL.parents[1]
PROJECT = SUPER / "Project"


def key(b): return re.sub(r"[^A-Za-z0-9]", "", b or "") or "Brandless"


def opt(a, name, default=None):
    return a[a.index(name) + 1] if name in a and a.index(name) + 1 < len(a) else default


def say(d, code=0):
    print(json.dumps(d, ensure_ascii=False)); sys.exit(code)


def folder_of(arg):
    p = Path(arg).expanduser()
    p = (p if p.is_absolute() else SUPER / p).resolve()
    if not (p.is_relative_to(PROJECT) and p.parent.name == "carousels"):
        sys.exit(f"not a carousel folder (Project/<BrandName>/carousels/<name>/): {p}")
    if not p.is_dir(): sys.exit(f"no carousel folder at {p}: run `new` first")
    return p


def meta_path(folder): return folder.parents[1] / "metadata" / f"{folder.name}.json"


class Meta:
    """The metadata file, read and written under a lock (two jobs may finish at once)."""
    def __init__(self, folder):
        self.path = meta_path(folder)
        self.lock = open(folder / ".metadata.lock", "a")   # kept in the carousel folder, never in metadata/
    def __enter__(self):
        fcntl.flock(self.lock, fcntl.LOCK_EX)
        self.d = json.loads(self.path.read_text()) if self.path.is_file() else {}
        return self.d
    def __exit__(self, *exc):
        if exc[0] is None:
            tmp = self.path.with_name(self.path.stem + ".saving.json")
            tmp.write_text(json.dumps(self.d, indent=1, ensure_ascii=False) + "\n"); os.replace(tmp, self.path)
        fcntl.flock(self.lock, fcntl.LOCK_UN); self.lock.close()


def total(jobs): return round(sum(j.get("credits") or 0 for j in jobs), 2)


def new(a):
    if len(a) < 3 or "--brand-number" not in a: sys.exit(__doc__)
    brand, task = a[1], a[2].strip()
    if not task.isdigit(): sys.exit("the Task ID must be a number")
    bk = key(brand)
    root = PROJECT / bk
    # a resumed session: the carousel already made for this Task ID
    for m in sorted((root / "metadata").glob(f"{task}-*.json")) if (root / "metadata").is_dir() else []:
        try: d = json.loads(m.read_text())
        except (OSError, ValueError): continue
        if d.get("output_type") == "carousel" and str(d.get("task_id")) == task and Path(d.get("folder", "")).is_dir():
            say({"folder": d["folder"], "metadata": str(m), "name": d["name"], "started": d.get("started"), "resumed": True})
    now = datetime.now()
    name = f"{task}-{bk.lower()}-{now:%m-%d}"
    folder = root / "carousels" / name
    for sub in ("research", "gen", "out", "deletable"): (folder / sub).mkdir(parents=True, exist_ok=True)
    (root / "metadata").mkdir(parents=True, exist_ok=True)
    with Meta(folder) as d:
        d.update({"root": str(root), "task_id": task, "brand_number": opt(a, "--brand-number"), "name": name,
                  "brand": bk, "output_type": "carousel", "product": opt(a, "--product") or None,
                  "website": opt(a, "--website") or None, "angle": opt(a, "--angle") or None,
                  "created": now.strftime("%Y-%m-%d"), "started": now.isoformat(timespec="seconds"),
                  "folder": str(folder), "slides_html": str(folder / "slides.html"),
                  "out": [], "contact": str(folder / "out" / "contact.png"), "notes": str(folder / "out" / "notes.md"),
                  "jobs": [], "total_credits": 0})
    say({"folder": str(folder), "metadata": str(meta_path(folder)), "name": name, "started": now.isoformat(timespec="seconds")})


def sh(script, *args, env=None):
    r = subprocess.run(["bash", str(TOOLS / script), *map(str, args)], text=True, capture_output=True,
                       env={**os.environ, **(env or {})}, stdin=subprocess.DEVNULL)
    sys.stdout.write(r.stdout); sys.stderr.write(r.stderr)
    return r


def record_job(folder, a):
    if len(a) < 5: sys.exit(__doc__)
    try: credits = float(a[3])
    except ValueError: sys.exit("credits must be a number")
    job = {"jobId": a[2], "model": opt(a, "--model", "gpt-image-2"), "resultUrl": opt(a, "--url"),
           "credits": credits, "credits_source": "price", "status": opt(a, "--status", "COMPLETED"),
           "out": a[4], "prompt": opt(a, "--prompt"), "created": datetime.now().isoformat(timespec="seconds")}
    jobs_log = folder / "jobs.jsonl"
    with open(jobs_log, "a", encoding="utf-8") as f: f.write(json.dumps(job, ensure_ascii=False) + "\n")
    new_jobs = [job]
    with Meta(folder) as d:
        known = {(j.get("jobId"), j.get("created")) for j in d.get("jobs", [])}
        d.setdefault("jobs", []).extend(j for j in new_jobs if (j.get("jobId"), j.get("created")) not in known)
        d["total_credits"] = total(d["jobs"])
        tc = d["total_credits"]
    print(json.dumps({"recorded_jobs": len(new_jobs), "total_credits": tc}))


def slides_in(folder): return sorted((folder / "out").glob("slide-*.jpg"))


def check(folder):
    from PIL import Image
    problems = []
    mp = meta_path(folder)
    d = json.loads(mp.read_text()) if mp.is_file() else {}
    if not d: problems.append("no metadata")
    sl = slides_in(folder)
    if not 4 <= len(sl) <= 7: problems.append(f"{len(sl)} slides (4 to 7 expected)")
    nums = [int(re.search(r"(\d+)", s.stem).group(1)) for s in sl]
    if nums != list(range(1, len(sl) + 1)): problems.append(f"slides not numbered 01..{len(sl):02d}: {[s.name for s in sl]}")
    for s in sl:
        try:
            with Image.open(s) as im:
                if im.size != (1080, 1350): problems.append(f"{s.name} is {im.size[0]}x{im.size[1]}, not 1080x1350")
        except OSError as e: problems.append(f"{s.name} unreadable: {e}")
    if not (folder / "out" / "contact.png").is_file(): problems.append("no out/contact.png")
    notes = folder / "out" / "notes.md"
    if not notes.is_file(): problems.append("no out/notes.md")
    elif "caption" not in notes.read_text(encoding="utf-8").lower(): problems.append("out/notes.md has no captions")
    if not (folder / "slides.html").is_file(): problems.append("no slides.html")
    if d and any(j.get("credits") is None for j in d.get("jobs", [])): problems.append("a job has no credits recorded")
    return {"ok": not problems, "folder": str(folder), "slides": len(sl), "total_credits": total(d.get("jobs", [])),
            "problems": problems}


def finish(folder, a):
    with Meta(folder) as d:
        d["out"] = [str(s) for s in slides_in(folder)]
        d["slides"] = len(d["out"])
        d["total_credits"] = total(d.get("jobs", []))
        for k in ("theme", "headline"):
            if opt(a, f"--{k}"): d[k] = opt(a, f"--{k}")
        now = datetime.now(); d["finished"] = now.isoformat(timespec="seconds")
        try: d["minutes"] = round((now - datetime.fromisoformat(d["started"])).total_seconds() / 60)
        except (KeyError, ValueError): d["minutes"] = None
        res = {"folder": str(folder), "slides": d["slides"], "total_credits": d["total_credits"], "minutes": d["minutes"]}
    say(res)


def main():
    a = sys.argv[1:]
    if not a: sys.exit(__doc__)
    cmd = a[0]
    if cmd == "new": return new(a)
    if len(a) < 2: sys.exit(__doc__)
    folder = folder_of(a[1])
    if cmd == "scrape" and len(a) == 3:
        r = sh("scrape.sh", a[2], folder / "research"); sys.exit(r.returncode)
    if cmd == "record-job": return record_job(folder, a)
    if cmd == "render" and len(a) in (3, 4):
        r = sh("render.sh", folder / "slides.html", folder / "out", *a[2:]); sys.exit(r.returncode)
    if cmd == "check":
        res = check(folder); say(res, 0 if res["ok"] else 1)
    if cmd == "finish": return finish(folder, a)
    sys.exit(__doc__)


if __name__ == "__main__":
    main()
